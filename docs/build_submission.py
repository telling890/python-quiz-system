def rich(doc, parts, size=10.5, indent=True):
    """一段里混排「普通 + 加粗」：parts 是 [(文字, 是否加粗), ...]。"""
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    for text, bold in parts:
        cn(p.add_run(text), "宋体", size, bold)
    return p


def _save(doc, name):
    path = os.path.join(HERE, name)
    doc.save(path)
    return path


